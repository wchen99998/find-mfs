const COMMON_FRAGMENT_NORMALIZATION: f64 = 0.16554708331150958;
const COMMON_LOSS_NORMALIZATION: f64 = 1.5;
const COMMON_ROOT_LOSS_NORMALIZATION: f64 = 0.0;

pub fn default_sirius_like_tables() -> &'static SiriusLikeTables {
    static TABLES: OnceLock<SiriusLikeTables> = OnceLock::new();
    TABLES.get_or_init(|| SiriusLikeTables {
        common_fragments: map_from_pairs(COMMON_FRAGMENTS),
        common_losses: map_from_pairs(COMMON_LOSSES),
        recombined_common_losses: map_from_pairs(RECOMBINED_COMMON_LOSSES),
        recombined_common_loss_overrides: map_from_pairs(RECOMBINED_COMMON_LOSS_OVERRIDES),
        common_radicals: map_from_pairs(COMMON_RADICALS),
        common_root_losses: map_from_pairs(COMMON_ROOT_LOSSES),
        strange_fragment_whitelist: set_from_slice(STRANGE_FRAGMENT_WHITELIST),
        strange_losses: set_from_slice(STRANGE_LOSSES),
        common_fragment_normalization: COMMON_FRAGMENT_NORMALIZATION,
        common_loss_normalization: COMMON_LOSS_NORMALIZATION,
        common_root_loss_normalization: COMMON_ROOT_LOSS_NORMALIZATION,
    })
}

fn map_from_pairs(pairs: &[(&str, f64)]) -> HashMap<String, f64> {
    pairs
        .iter()
        .map(|(key, value)| ((*key).to_string(), *value))
        .collect()
}

fn set_from_slice(values: &[&str]) -> HashSet<String> {
    values.iter().map(|value| (*value).to_string()).collect()
}
